"""Thin ctypes bindings for the Win32 calls the monitor needs.

Import-safe on non-Windows platforms: the DLL handles are ``None`` and callers
must check :data:`AVAILABLE` before using them.
"""
from __future__ import annotations

import ctypes
import sys
from ctypes import wintypes

AVAILABLE = sys.platform == "win32"

if AVAILABLE:
    user32 = ctypes.WinDLL("user32", use_last_error=True)
    kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
    gdi32 = ctypes.WinDLL("gdi32", use_last_error=True)
    try:
        dwmapi = ctypes.WinDLL("dwmapi", use_last_error=True)
    except OSError:  # pragma: no cover
        dwmapi = None
else:  # pragma: no cover
    user32 = kernel32 = gdi32 = dwmapi = None

